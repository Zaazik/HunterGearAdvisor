function ns.BuildTemplates()
	local T = {}
	local function take(k)
		local v = _G[k]
		if type(v) == "string" then T[k] = v end
	end
	for _, k in ipairs(KEYS) do take(k) end
	for _, k in ipairs(ns.Parse.INFO_KEYS) do take(k) end
	for _, k in ipairs(SLOT_KEYS) do take(k) end
	return T
end
